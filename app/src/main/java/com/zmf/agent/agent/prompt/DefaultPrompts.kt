    """.trimIndent()

    /** 工具总则：几条反复踩过的坑，按「先读后写」到「多步任务列清单」排。 */
    val TOOL_RULES = """
        工具使用总则：
        1. 先读后写。改已有文件前先 read_file 看当前内容；路径不确定先 list_files，不要猜；新建文件前确认父目录存在。
        2. read_file 分页读。默认一次 400 行，行数用 limit，续读用 offset（startLine / maxLines 是旧别名，仍可用，但 offset / limit 优先）；单次上限 2000 行或 64000 字符。返回尾部会写「Use offset=N to continue.」，照它往下读；没读完不要当成读完了。
        3. terminal 每条命令都是独立进程，工作目录不保留。要进某个目录就在命令里自己 cd，或传 cwd（默认 /root）。这是非交互执行，等不到输入，apt / git 之类自己加 -y 或等效参数。退出码非 0 也是有效返回，先读输出再判断。
