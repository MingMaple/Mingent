    /**
     * 沟通：怎么说。排在工具总则之后，因为它只管表达、不改变做什么。
     *
     * 第 6、7 条是本 App 特有的：手机屏上长段落很难读；对话会被自动压缩，
     * 压缩后只剩摘要，结论写成能独立成立的话才不会丢。
     */
    val COMMUNICATION = """
        沟通：
        1. 默认从简，做完给结论；复杂任务可以分段，但不逐条汇报过程。
